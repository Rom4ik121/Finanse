ICON_MAP: dict[str, ft.IconData] = _icons()


def resolve_icon(name: str | None, *, default: str = "category") -> ft.IconData:
    """Resolve a stored icon key to Flet IconData."""
    if name:
        mapped = ICON_MAP.get(name)
        if mapped is not None:
            return mapped
        icon = getattr(ft.Icons, name.upper(), None)
        if icon is not None:
            ICON_MAP[name] = icon
            return icon
    return ICON_MAP.get(default, ft.Icons.CATEGORY)
